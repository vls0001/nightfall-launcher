#!/usr/bin/env python3
"""Generates logo drawables and Brands.java from brands.json.

Usage: python3 gen.py <path to an unpacked simple-icons npm package>
Needs: pip install svgelements
"""
import json
import os
import re
import sys

from svgelements import Close, CubicBezier, Line, Move, Path, QuadraticBezier

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
DRAWABLES = os.path.join(ROOT, "res", "drawable")
JAVA = os.path.join(ROOT, "src", "dev", "nightfall", "launcher", "Brands.java")


def num(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def pt(p):
    return f"{num(p.x)},{num(p.y)}"


def android_path(d):
    """Plain absolute M/L/C/Q/Z path that every Android version parses (no arcs, no compact flags)."""
    path = Path(d)
    path.approximate_arcs_with_cubics()
    out = []
    for seg in path:
        if isinstance(seg, Move):
            out.append("M" + pt(seg.end))
        elif isinstance(seg, Close):
            out.append("Z")
        elif isinstance(seg, Line):
            out.append("L" + pt(seg.end))
        elif isinstance(seg, CubicBezier):
            out.append("C" + " ".join(pt(p) for p in (seg.control1, seg.control2, seg.end)))
        elif isinstance(seg, QuadraticBezier):
            out.append("Q" + " ".join(pt(p) for p in (seg.control, seg.end)))
        else:
            raise ValueError(f"unexpected segment {seg!r}")
    return "".join(out)


def color(hex6):
    return "0xFF" + hex6.upper()


def main():
    si = sys.argv[1]
    brands = json.load(open(os.path.join(HERE, "brands.json")))["brands"]

    for f in os.listdir(DRAWABLES):
        if f.startswith("logo_"):
            os.remove(os.path.join(DRAWABLES, f))

    entries = []
    for b in brands:
        res = "0"
        if b.get("icon"):
            slug = b["icon"]
            svg = open(os.path.join(si, "icons", slug + ".svg")).read()
            d = re.search(r'<path d="([^"]+)"', svg).group(1)
            name = "logo_" + re.sub(r"[^a-z0-9_]", "_", slug)
            # Trim to the logo's own bounds so wide wordmarks keep their shape and everything centres.
            x0, y0, x1, y1 = Path(d).bbox()
            w, h = x1 - x0, y1 - y0
            with open(os.path.join(DRAWABLES, name + ".xml"), "w") as out:
                out.write(
                    '<?xml version="1.0" encoding="utf-8"?>\n'
                    f'<!-- {b["name"]} logo from Simple Icons (CC0), slug "{slug}". Generated by tools/logos/gen.py. -->\n'
                    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                    f'    android:width="{num(24 * w / h)}dp" android:height="24dp"\n'
                    f'    android:viewportWidth="{num(w)}" android:viewportHeight="{num(h)}">\n'
                    f'    <group android:translateX="{num(-x0)}" android:translateY="{num(-y0)}">\n'
                    f'        <path android:fillColor="#FFFFFFFF" android:pathData="{android_path(d)}" />\n'
                    "    </group>\n"
                    "</vector>\n")
            res = "R.drawable." + name
        pk = ", ".join(json.dumps(p) for p in b.get("packages", []))
        lb = ", ".join(json.dumps(l.lower()) for l in b.get("labels", []))
        entries.append(
            f'        add({json.dumps(b["name"])}, {res}, {str(bool(b.get("wordmark"))).lower()}, '
            f'{color(b.get("logo", "FFFFFF"))}, '
            f'{color(b.get("text", "FFFFFF"))}, {color(b["bg"][0])}, {color(b["bg"][1])},\n'
            f"                new String[]{{{pk}}},\n"
            f"                new String[]{{{lb}}});")

    java = '''package dev.nightfall.launcher;

import java.util.HashMap;
import java.util.Locale;
import java.util.Map;

/**
 * Brand artwork for apps that don't ship a wide TV banner.
 * GENERATED by tools/logos/gen.py from tools/logos/brands.json; edit those, not this file.
 * Logos: Simple Icons (https://simpleicons.org), CC0. Brand names and logos belong to their owners.
 */
final class Brands {
    static final class Brand {
        final String name;
        final int logoRes; // 0 = name-only tile
        final boolean wordmark; // logo already spells the name
        final int logoColor;
        final int textColor;
        final int[] bg;

        Brand(String name, int logoRes, boolean wordmark, int logoColor, int textColor, int bg0, int bg1) {
            this.name = name;
            this.logoRes = logoRes;
            this.wordmark = wordmark;
            this.logoColor = logoColor;
            this.textColor = textColor;
            this.bg = new int[]{bg0, bg1};
        }
    }

    private static final Map<String, Brand> BY_PACKAGE = new HashMap<String, Brand>();
    private static final Map<String, Brand> BY_LABEL = new HashMap<String, Brand>();

    private Brands() {
    }

    /** The brand for an app, matched by package name first, then by its label. */
    static Brand find(String pkg, String label) {
        Brand b = BY_PACKAGE.get(pkg);
        if (b == null && label != null) b = BY_LABEL.get(label.trim().toLowerCase(Locale.ROOT));
        return b;
    }

    private static void add(String name, int logoRes, boolean wordmark, int logoColor, int textColor,
                            int bg0, int bg1, String[] packages, String[] labels) {
        Brand b = new Brand(name, logoRes, wordmark, logoColor, textColor, bg0, bg1);
        for (String p : packages) BY_PACKAGE.put(p, b);
        for (String l : labels) BY_LABEL.put(l, b);
    }

    static {
''' + "\n".join(entries) + '''
    }
}
'''
    open(JAVA, "w").write(java)
    print(f"{len(brands)} brands, {sum(1 for b in brands if b.get('icon'))} logos")


if __name__ == "__main__":
    main()
